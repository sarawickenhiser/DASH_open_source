def prefixed_tool_joint_names(prefix: str | None) -> tuple[str, ...]:
    """The four H4HR joint names, optionally prefixed.

    ``/h4hr/joint_command`` and ``/joint_states`` are absolute, unnamespaced,
    and read BY JOINT NAME, so two instruments on one ROS graph drive each
    other (SYSTEM_CONTEXT section 8.5, open item 7).  A prefix separates them on
    the same topics, which is the same device ``publish_sim_arm`` uses for
    ``/humanoid_rcm/sim_arm`` and invents no topic.

    An empty prefix returns exactly ``H4HR_JOINT_NAMES``, so every existing
    single-instrument run is unchanged.  It is a property of the RUN, not of the
    arm: it is passed in rather than read from a config, so a config that works
    alone keeps working alone.
    """
    if not prefix:
        return H4HR_JOINT_NAMES
    return tuple(f"{prefix}{name}" for name in H4HR_JOINT_NAMES)


