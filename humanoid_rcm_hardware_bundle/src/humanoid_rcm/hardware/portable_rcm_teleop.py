# Controller faults that describe a momentary demand the arm cannot meet
# rather than broken geometry. The arm holds for as long as one of these is
# raised and resumes by itself when the demand becomes reachable again; it is
# latched into a real fault only if it will not clear (see
# hardware.runtime.max_transient_fault_cycles).
RECOVERABLE_FAULTS = frozenset(
    {"real-time QP could not satisfy hard RCM and joint bounds"}
)

# Recoverable faults whose message carries MEASURED NUMBERS, so they can never
# be matched by equality against the set above.
#
# The shaft-segment guard is the case, and leaving it out was a latent trap:
# 9.11 made that message name the bound and the excess ("...shaft parameter
# 160 mm past the 160 mm bound by 0 mm"), which silently took it out of reach
# of any frozenset lookup even if someone had thought to add it. Matching on
# the stable prefix is what keeps a parameterised message classifiable.
RECOVERABLE_FAULT_PREFIXES = (
    "RCM no longer lies on the physical shaft segment",
)


def is_recoverable_fault(reason: str) -> bool:
    """Will this fault clear on its own once the operator eases the master back?

    The shaft-segment guard belongs here for exactly the reason the infeasible
    QP does, and the argument is the one already written at the call site: the
    arm is HELD for the cycle either way, and backing the master off restores
    the geometry on the very next one. Latching the whole session on the first
    cycle is what does not follow -- pulling the tool back out raises the shaft
    parameter above the bound immediately, so "the geometry really is stuck" is
    a claim about many consecutive cycles, not about one.

    Holding is not ignoring. The controller returns zero velocity, `q_command`
    does not advance, and the run still latches if the condition persists past
    `max_transient_fault_cycles`.
    """
    return (
        reason in RECOVERABLE_FAULTS
        or reason.startswith(RECOVERABLE_FAULT_PREFIXES)
    )


def _finite_vector(value: ArrayLike, size: int, name: str) -> Vector:
    vector = np.asarray(value, dtype=float).reshape(-1)
    if vector.shape != (size,) or not np.all(np.isfinite(vector)):
        raise ValueError(f"{name} must contain {size} finite values")
    return vector


def _clip_norm(vector: Vector, maximum: float) -> Vector:
    norm = float(np.linalg.norm(vector))
    if norm <= maximum or norm <= 1e-15:
        return vector
    return (maximum / norm) * vector


def quaternion_xyzw_to_rotation(quaternion: ArrayLike) -> Matrix:
    """Convert a ROS-order quaternion to a proper rotation matrix."""
    x, y, z, w = _finite_vector(quaternion, 4, "quaternion")
    norm = float(np.linalg.norm((x, y, z, w)))
    if norm < 1e-9:
        raise ValueError("quaternion is near zero")
    x, y, z, w = np.array((x, y, z, w)) / norm
    return np.array(
        [
            [1.0 - 2.0 * (y * y + z * z), 2.0 * (x * y - w * z), 2.0 * (x * z + w * y)],
            [2.0 * (x * y + w * z), 1.0 - 2.0 * (x * x + z * z), 2.0 * (y * z - w * x)],
            [2.0 * (x * z - w * y), 2.0 * (y * z + w * x), 1.0 - 2.0 * (x * x + y * y)],
        ]
    )


def euler_zyx_rotation(rpy_rad: ArrayLike) -> Matrix:
    """Return ``Rz(yaw) @ Ry(pitch) @ Rx(roll)``."""
    roll, pitch, yaw = _finite_vector(rpy_rad, 3, "alignment RPY")
    return (
        axis_angle_rotation((0.0, 0.0, 1.0), yaw)
        @ axis_angle_rotation((0.0, 1.0, 0.0), pitch)
        @ axis_angle_rotation((1.0, 0.0, 0.0), roll)
    )


def scale_rotation(rotation: ArrayLike, scale: float) -> Matrix:
    """Scale a relative rotation along its axis-angle geodesic."""
    matrix = np.asarray(rotation, dtype=float).reshape(3, 3)
    vector = rotation_error(matrix, np.eye(3))
    angle = float(np.linalg.norm(vector))
    if angle < 1e-12:
        return np.eye(3)
    return axis_angle_rotation(vector / angle, float(scale) * angle)


def orthonormalize_rotation(rotation: ArrayLike) -> Matrix:
    matrix = np.asarray(rotation, dtype=float).reshape(3, 3)
    left, _, right = np.linalg.svd(matrix)
    if np.linalg.det(left @ right) < 0.0:
        left[:, -1] *= -1.0
    return left @ right


@dataclass(frozen=True)
class PsmMapping:
    """Coordinate boundary between the MJCF model and H4HR joint controller."""

    joint_signs: Vector
    mtm_grip_open_rad: float
    mtm_grip_closed_rad: float
    h4hr_open_grip_rad: float
    h4hr_closed_grip_rad: float

    def __post_init__(self) -> None:
        signs = _finite_vector(self.joint_signs, 3, "PSM joint signs")
        if not np.all(np.isin(signs, (-1.0, 1.0))):
            raise ValueError("PSM joint signs must each be +1 or -1")
        if abs(self.mtm_grip_open_rad - self.mtm_grip_closed_rad) < 1e-6:
            raise ValueError("MTM gripper endpoints must differ")
        if abs(self.h4hr_open_grip_rad - self.h4hr_closed_grip_rad) < 1e-6:
            raise ValueError("H4HR grip endpoints must differ")
        object.__setattr__(self, "joint_signs", signs)

    def hardware_to_model(self, positions: ArrayLike) -> Vector:
        """H4HR roll/pitch/yaw radians -> model roll/pitch/yaw radians."""
        return self.joint_signs * _finite_vector(positions, 3, "PSM hardware positions")

    def model_to_hardware(self, positions: ArrayLike) -> Vector:
        """Model roll/pitch/yaw radians -> H4HR roll/pitch/yaw radians."""
        return self.joint_signs * _finite_vector(positions, 3, "PSM model positions")

    def gripper_to_h4hr(self, gripper_angle: float) -> float:
        angle = float(gripper_angle)
        if not np.isfinite(angle):
            raise ValueError("MTM gripper angle must be finite")
        span = self.mtm_grip_open_rad - self.mtm_grip_closed_rad
        open_fraction = float(
            np.clip((angle - self.mtm_grip_closed_rad) / span, 0.0, 1.0)
        )
        return self.h4hr_closed_grip_rad + open_fraction * (
            self.h4hr_open_grip_rad - self.h4hr_closed_grip_rad
        )


@dataclass(frozen=True)
class RosSnapshot:
    mtm_position: Vector | None
    mtm_rotation: Matrix | None
    mtm_pose_sequence: int
    mtm_pose_time: float
    gripper_angle: float | None
    gripper_time: float
    clutch_pressed: bool
    rcm_point: Vector | None
    psm_hardware_positions: Vector | None
    psm_grip_position: float | None
    psm_state_time: float
    enable_requested: bool
    estop_latched: bool
    # Cartesian command inputs, read by AbsoluteTipSetpointSource and ignored by
    # the MTM path.  Defaulted because visualize_setup.py builds this positionally
    # from the original thirteen fields and must keep working untouched.
    #
    # The absolute pair is a LATCHED goal: the newest one wins and re-reading it
    # is harmless.  The relative pair is CONSUMED -- snapshot() drains it -- so
    # deltas arriving between two control cycles accumulate (summed in position,
    # composed in rotation) rather than being lost or replayed.  snapshot() is
    # called exactly once per cycle, which is what makes draining there correct.
    command_position: Vector | None = None
    command_rotation: Matrix | None = None
    command_sequence: int = 0
    command_time: float = 0.0
    command_delta_position: Vector | None = None
    command_delta_rotation: Matrix | None = None


class CommandSource(Protocol):
    """Produces the tip setpoint the Cartesian controller tracks.

    The first three methods are ``IncrementalMtmMapper``'s existing signatures
    verbatim, so the call sites in ``run_hardware`` do not change when the source
    does.  ``readiness`` and ``status`` are the additions that matter:

    * ``readiness`` moves the input-specific half of ``_ros_ready`` INTO the
      source, because only the source knows what a stale input means.  For a
      master handle the pose IS the command and staleness must stop the arm; for
      a setpoint source silence means "hold the last goal" and stopping is wrong.
    * ``status`` reports a non-fault condition -- a commander that has gone quiet
      -- so it can reach the console without faulting the run.
    """

    def reset(self, target: ToolTipSetpoint, snapshot: RosSnapshot) -> None:
        """Seed the source at ``target``, the MEASURED tip pose at handover."""

    def accept_target(self, target: ToolTipSetpoint) -> None:
        """Feed anti-windup's achievable target back into the integrator."""

    def update(
        self, snapshot: RosSnapshot, now: float
    ) -> tuple[ToolTipSetpoint, Vector]:
        """Return this cycle's tip setpoint and its feed-forward twist."""

    def readiness(
        self, snapshot: RosSnapshot, now: float, state_timeout: float
    ) -> tuple[bool, str]:
        """Whether this source's own inputs are usable, and why not."""

    def status(self) -> str:
        """A short non-fault note for the console, or an empty string."""


class IncrementalMtmMapper:
    """Incrementally map MTM motion to a Cartesian tool-tip setpoint.

    Incremental mapping makes clutching jump-free: while clutch is pressed the
    master reference follows the handle but the slave target does not move.
    """

    def __init__(
        self,
        *,
        translation_matrix: ArrayLike,
        translation_scale: float,
        rotation_alignment: ArrayLike,
        rotation_scale: float,
        max_linear_speed: float,
        max_angular_speed: float,
        twist_hold_seconds: float,
    ) -> None:
        self.translation_matrix = np.asarray(translation_matrix, dtype=float).reshape(
            3, 3
        )
        if not np.all(np.isfinite(self.translation_matrix)):
            raise ValueError("MTM translation matrix must be finite")
        self.translation_scale = float(translation_scale)
        self.rotation_alignment = np.asarray(rotation_alignment, dtype=float).reshape(
            3, 3
        )
        self.rotation_scale = float(rotation_scale)
        self.max_linear_speed = float(max_linear_speed)
        self.max_angular_speed = float(max_angular_speed)
        self.twist_hold_seconds = float(twist_hold_seconds)
        if (
            min(
                self.translation_scale,
                self.rotation_scale,
                self.max_linear_speed,
                self.max_angular_speed,
                self.twist_hold_seconds,
            )
            <= 0.0
        ):
            raise ValueError(
                "MTM mapping scales, speeds and hold time must be positive"
            )
        self.target: ToolTipSetpoint | None = None
        self._master_position: Vector | None = None
        self._master_rotation: Matrix | None = None
        self._sequence = -1
        self._sample_time = 0.0
        self._twist = np.zeros(6)
        self._twist_time = 0.0

    def reset(self, target: ToolTipSetpoint, snapshot: RosSnapshot) -> None:
        if snapshot.mtm_position is None or snapshot.mtm_rotation is None:
            raise ValueError("cannot reset MTM mapping without a pose sample")
        self.target = ToolTipSetpoint(target.position.copy(), target.rotation.copy())
        self._master_position = snapshot.mtm_position.copy()
        self._master_rotation = snapshot.mtm_rotation.copy()
        self._sequence = snapshot.mtm_pose_sequence
        self._sample_time = snapshot.mtm_pose_time
        self._twist.fill(0.0)
        self._twist_time = snapshot.mtm_pose_time

    def accept_target(self, target: ToolTipSetpoint) -> None:
        """Feed anti-windup's achievable target back into the master integrator."""
        self.target = ToolTipSetpoint(target.position.copy(), target.rotation.copy())

    def update(
        self, snapshot: RosSnapshot, now: float
    ) -> tuple[ToolTipSetpoint, Vector]:
        if (
            self.target is None
            or self._master_position is None
            or self._master_rotation is None
        ):
            raise RuntimeError("MTM mapper must be reset before update")
        new_sample = snapshot.mtm_pose_sequence != self._sequence
        if new_sample:
            if snapshot.mtm_position is None or snapshot.mtm_rotation is None:
                raise RuntimeError("MTM sample sequence advanced without a pose")
            sample_dt = max(snapshot.mtm_pose_time - self._sample_time, 1e-4)
            previous_target = self.target
            if snapshot.clutch_pressed:
                next_target = previous_target
                raw_twist = np.zeros(6)
            else:
                master_delta = snapshot.mtm_position - self._master_position
                slave_delta = (
                    self.translation_scale * self.translation_matrix @ master_delta
                )
                relative_rotation = self._master_rotation.T @ snapshot.mtm_rotation
                relative_vector = rotation_error(relative_rotation, np.eye(3))
                if (
                    np.linalg.norm(slave_delta) < 1e-12
                    and np.linalg.norm(relative_vector) < 1e-12
                ):
                    next_target = previous_target
                    raw_twist = np.zeros(6)
                else:
                    scaled_relative = scale_rotation(
                        relative_rotation, self.rotation_scale
                    )
                    tool_relative = (
                        self.rotation_alignment
                        @ scaled_relative
                        @ self.rotation_alignment.T
                    )
                    next_rotation = orthonormalize_rotation(
                        previous_target.rotation @ tool_relative
                    )
                    next_target = ToolTipSetpoint(
                        previous_target.position + slave_delta,
                        next_rotation,
                    )
                    raw_twist = np.concatenate(
                        (
                            _clip_norm(slave_delta / sample_dt, self.max_linear_speed),
                            _clip_norm(
                                rotation_error(next_rotation, previous_target.rotation)
                                / sample_dt,
                                self.max_angular_speed,
                            ),
                        )
                    )
            self.target = next_target
            self._twist = raw_twist
            self._twist_time = snapshot.mtm_pose_time
            self._master_position = snapshot.mtm_position.copy()
            self._master_rotation = snapshot.mtm_rotation.copy()
            self._sequence = snapshot.mtm_pose_sequence
            self._sample_time = snapshot.mtm_pose_time
        if snapshot.clutch_pressed or now - self._twist_time > self.twist_hold_seconds:
            twist = np.zeros(6)
        else:
            twist = self._twist.copy()
        return self.target, twist

    def readiness(
        self, snapshot: RosSnapshot, now: float, state_timeout: float
    ) -> tuple[bool, str]:
        """The master pose IS the command, so a stale one must stop the arm.

        These two checks and their exact strings were lifted out of
        ``_ros_ready`` unchanged.  A ``--command-source mtm`` run must stay
        behaviourally identical to every run that came before this refactor.
        """
        if snapshot.mtm_position is None or snapshot.mtm_rotation is None:
            return False, "waiting for MTM pose"
        if now - snapshot.mtm_pose_time > state_timeout:
            return False, "MTM pose is stale"
        return True, "ready"

    def status(self) -> str:
        return ""


class AbsoluteTipSetpointSource:
    """Track base-frame tip POSE commands instead of a master handle.

    Consumes an absolute goal (``servo_cp``) and one-shot deltas
    (``servo_cp_rel``), both in the base frame, and returns the same
    ``(ToolTipSetpoint, twist)`` pair ``IncrementalMtmMapper`` does -- so the
    call sites, the anti-windup feedback and every controller below are
    untouched.

    THIS IS AN INTEGRATOR, NOT A PASSTHROUGH.  Three separate reasons, each
    sufficient on its own:

    * ``accept_target`` hands back the setpoint the QP could actually accept.
      Recomputing the setpoint from the goal every cycle would overwrite that
      correction, error would build past the controller's
      ``max_position_target_lead_m`` clamp, and the arm would lurch when the goal
      was finally reached.  The integrator IS what anti-windup corrects.
    * The corrective velocity ceiling is ``position_gain * lead`` -- 3.0 * 0.012
      = 36 mm/s on the shipped config -- so a bare pose is slow.  Real speed
      comes from the feed-forward twist, and a twist only exists if something
      knows how far the setpoint moved this cycle.
    * Absolute and relative then share one path: one sets the goal, the other
      nudges it.

    WHY THIS SOURCE NEEDS NO HEARTBEAT.  ``reset`` seeds the goal from the
    MEASURED tip -- the caller passes forward kinematics in -- so an arm that has
    never been commanded holds its own pose at zero twist.  Silence therefore
    means "hold the last goal", which is well defined.  That is the opposite of a
    master handle, where a stale pose means the command is unknown and stopping
    is the only safe answer.  So ``readiness`` is unconditionally true, and
    ``state_timeout`` (0.10 s) never fires against the commanding process -- which
    matters because a 10 Hz stepping client publishes exactly at that period and
    would fault an actively moving arm on any Python hiccup.

    What still stops the arm, all unchanged: the arm-state half of
    ``_ros_ready``, ``/humanoid_rcm/enable`` going false, ``/h4hr/estop``, a
    stale ``rt/lowstate``, and ``max_absolute_step_m`` bounding how far a goal
    may sit ahead of the tip so a commander that dies mid-move cannot run on.
    That last one is the ONLY bound on unattended travel, and it is why
    ``command_timeout_s`` reports rather than acts: see ``update``.

    **That argument depends entirely on commands being SETPOINTS.  Do not add a
    velocity or jog mode here.**  The moment silence means "keep moving", the
    heartbeat becomes mandatory again and this whole design collapses.
    """

    def __init__(
        self,
        *,
        max_linear_speed: float,
        max_angular_speed: float,
        max_absolute_step_m: float,
        max_relative_step_m: float,
        max_step_rad: float,
        command_timeout_s: float,
        honor_clutch: bool = False,
    ) -> None:
        self.max_linear_speed = float(max_linear_speed)
        self.max_angular_speed = float(max_angular_speed)
        self.max_absolute_step_m = float(max_absolute_step_m)
        self.max_relative_step_m = float(max_relative_step_m)
        self.max_step_rad = float(max_step_rad)
        self.command_timeout_s = float(command_timeout_s)
        self.honor_clutch = bool(honor_clutch)
        if (
            min(
                self.max_linear_speed,
                self.max_angular_speed,
                self.max_absolute_step_m,
                self.max_relative_step_m,
                self.max_step_rad,
                self.command_timeout_s,
            )
            <= 0.0
        ):
            raise ValueError("command source speeds, steps and timeout must be positive")
        self.target: ToolTipSetpoint | None = None
        self.goal: ToolTipSetpoint | None = None
        self._twist = np.zeros(6)
        self._sequence = -1
        self._update_time = 0.0
        self._command_time = 0.0
        self._commanded_once = False

    def reset(self, target: ToolTipSetpoint, snapshot: RosSnapshot) -> None:
        """Seed both the setpoint and the goal at the measured tip.

        ``snapshot`` is deliberately unused.  The seed at the call site is
        forward kinematics on the measured joints, which is why this source can
        arm with no commander connected at all: goal == setpoint == measured tip
        produces a stationary setpoint and zero twist, and the arm holds.
        """
        del snapshot
        self.target = ToolTipSetpoint(target.position.copy(), target.rotation.copy())
        self.goal = ToolTipSetpoint(target.position.copy(), target.rotation.copy())
        self._twist.fill(0.0)
        self._sequence = -1
        self._update_time = 0.0
        self._command_time = 0.0
        self._commanded_once = False

    def accept_target(self, target: ToolTipSetpoint) -> None:
        self.target = ToolTipSetpoint(target.position.copy(), target.rotation.copy())

    def _bounded_goal(
        self, position: ArrayLike, rotation: ArrayLike, maximum_step: float
    ) -> ToolTipSetpoint:
        """Bound how far ahead of the current setpoint a goal may sit.

        This is what keeps a commander that dies mid-move from running the arm
        on: unattended travel is at most ``maximum_step``, walked off at
        ``max_linear_speed``.  A caller wanting to go further re-sends, which is
        what the step client's ``settle`` helper is for.
        """
        assert self.target is not None
        goal_position = _finite_vector(position, 3, "command position")
        goal_rotation = orthonormalize_rotation(rotation)
        delta = goal_position - self.target.position
        distance = float(np.linalg.norm(delta))
        if distance > maximum_step:
            goal_position = self.target.position + delta * (maximum_step / distance)
        error = rotation_error(goal_rotation, self.target.rotation)
        angle = float(np.linalg.norm(error))
        if angle > self.max_step_rad:
            goal_rotation = (
                axis_angle_rotation(error / angle, self.max_step_rad)
                @ self.target.rotation
            )
        return ToolTipSetpoint(goal_position, goal_rotation)

    def update(
        self, snapshot: RosSnapshot, now: float
    ) -> tuple[ToolTipSetpoint, Vector]:
        if self.target is None or self.goal is None:
            raise RuntimeError("command source must be reset before update")
        dt = now - self._update_time if self._update_time else 0.0
        self._update_time = now

        if self.honor_clutch and snapshot.clutch_pressed:
            # Freeze the integrator rather than fault.  Off by default: the
            # pedal tray is shared between both arms and both wrists, so a foot
            # would silently stop a scripted bimanual sequence.
            self.goal = self.target
            self._twist.fill(0.0)
            return self.target, self._twist.copy()

        if snapshot.command_sequence != self._sequence:
            self._sequence = snapshot.command_sequence
            if (
                snapshot.command_position is not None
                and snapshot.command_rotation is not None
            ):
                self.goal = self._bounded_goal(
                    snapshot.command_position,
                    snapshot.command_rotation,
                    self.max_absolute_step_m,
                )
                self._commanded_once = True
                self._command_time = now

        if (
            snapshot.command_delta_position is not None
            or snapshot.command_delta_rotation is not None
        ):
            # Applied to the INTEGRATOR's goal, never to the measurement.
            # Jogging from the measured pose would close a loop over the whole
            # stack and double-count tracking lag on every step.
            delta_position = (
                np.zeros(3)
                if snapshot.command_delta_position is None
                else snapshot.command_delta_position
            )
            delta_rotation = (
                np.eye(3)
                if snapshot.command_delta_rotation is None
                else snapshot.command_delta_rotation
            )
            self.goal = self._bounded_goal(
                self.goal.position + delta_position,
                delta_rotation @ self.goal.rotation,
                self.max_relative_step_m,
            )
            self._commanded_once = True
            self._command_time = now

        # NOTE: a quiet commander is REPORTED (see ``status``) and nothing else.
        # Freezing the goal here was tried and is wrong: one absolute setpoint
        # sent once and never repeated is the most natural use of this API, and
        # truncating it part-way means the arm silently stops short of a pose it
        # accepted.  Unattended travel is already bounded -- by
        # ``max_absolute_step_m``, which caps how far ahead of the tip a goal
        # may sit -- so the freeze bought no safety and cost the semantics.
        position_error = self.goal.position - self.target.position
        distance = float(np.linalg.norm(position_error))
        orientation_error = rotation_error(self.goal.rotation, self.target.rotation)
        angle = float(np.linalg.norm(orientation_error))

        next_position = self.target.position
        next_rotation = self.target.rotation
        linear_velocity = np.zeros(3)
        angular_velocity = np.zeros(3)

        if dt > 0.0:
            if distance > 1e-12:
                direction = position_error / distance
                step = min(distance, self.max_linear_speed * dt)
                next_position = self.target.position + direction * step
                linear_velocity = direction * (step / dt)
            if angle > 1e-12:
                axis = orientation_error / angle
                step = min(angle, self.max_angular_speed * dt)
                next_rotation = orthonormalize_rotation(
                    axis_angle_rotation(axis, step) @ self.target.rotation
                )
                angular_velocity = axis * (step / dt)

        self.target = ToolTipSetpoint(next_position, next_rotation)
        self._twist = np.concatenate((linear_velocity, angular_velocity))
        return self.target, self._twist.copy()

    def readiness(
        self, snapshot: RosSnapshot, now: float, state_timeout: float
    ) -> tuple[bool, str]:
        """Always ready.  See the class docstring: silence is a held setpoint."""
        del snapshot, now, state_timeout
        return True, "ready"

    def status(self) -> str:
        if not self._commanded_once:
            return "no command yet"
        age = self._update_time - self._command_time
        if age > self.command_timeout_s:
            return f"commander silent {age:.1f}s"
        return ""


class UnitreeLowCmdArm:
    """Direct-lowcmd G1 transport matching the supplied prior control script.

    The class remains inert until ``connect`` and ``enable`` have both
    completed.  It captures every other joint at enable time and sends bounded
    position commands for ONE arm on ``rt/lowcmd``.

    **Which arm is `arm_indices`, and getting it wrong is the worst failure in
    this file.** Every layer above the transport is arm-agnostic -- the
    kinematics, the QP, the RCM constraint all work from joint names -- so a
    transport pointed at the other arm's motors produces confident, smooth,
    completely wrong motion that nothing downstream can detect. Build it with
    ``arm_indices_from_config``, which reads the same ``robot.active_joints``
    the kinematics were built from. The default stays right-handed so every
    existing caller is unchanged.
    """

    def __init__(
        self,
        network_interface: str,
        *,
        allow_motion: bool = False,
        control_dt: float = 0.004,
        max_joint_velocity: float = 0.35,
        state_timeout: float = 0.10,
        joint_gains: dict[Any, Any] | None = None,
        arm_indices: tuple[int, ...] = G1_RIGHT_ARM_INDICES,
    ) -> None:
        self.arm_indices = tuple(int(index) for index in arm_indices)
        if len(self.arm_indices) != 7 or any(
            index < 0 or index >= 29 for index in self.arm_indices
        ):
            raise ValueError("arm_indices must be seven G1 motor indices in 0..28")
        self.arm_side = (
            "left" if self.arm_indices == G1_LEFT_ARM_INDICES
            else "right" if self.arm_indices == G1_RIGHT_ARM_INDICES
            else "custom"
        )
        self.network_interface = str(network_interface)
        self.allow_motion = bool(allow_motion)
        self.joint_gains = {
            int(index): (float(pair[0]), float(pair[1]))
            for index, pair in (joint_gains or {}).items()
        }
        self.control_dt = float(control_dt)
        self.max_joint_velocity = float(max_joint_velocity)
        self.state_timeout = float(state_timeout)
        self._state_lock = threading.Lock()
        self._state: Any | None = None
        self._state_time = 0.0
        self._publisher: Any | None = None
        self._subscriber: Any | None = None
        self._command: Any | None = None
        self._crc: Any | None = None
        self._enabled = False
        self._last_command: Vector | None = None
        self._stop = threading.Event()
        self._reader_thread: threading.Thread | None = None

    def connect(self) -> None:
        try:
            from unitree_sdk2py.core.channel import (
                ChannelFactoryInitialize,
                ChannelPublisher,
                ChannelSubscriber,
            )
            from unitree_sdk2py.idl.default import unitree_hg_msg_dds__LowCmd_
            from unitree_sdk2py.idl.unitree_hg.msg.dds_ import LowCmd_, LowState_
            from unitree_sdk2py.utils.crc import CRC
        except ImportError as exc:  # pragma: no cover - hardware dependency
            raise RuntimeError(
                "install Unitree's unitree_sdk2_python before connecting to G1"
            ) from exc
        if self.network_interface:
            ChannelFactoryInitialize(0, self.network_interface)
        else:
            ChannelFactoryInitialize(0)
        self._publisher = ChannelPublisher("rt/lowcmd", LowCmd_)
        self._publisher.Init()
        self._subscriber = ChannelSubscriber("rt/lowstate", LowState_)
        self._subscriber.Init()
        self._command = unitree_hg_msg_dds__LowCmd_()
        self._crc = CRC()
        self._reader_thread = threading.Thread(
            target=self._read_loop,
            name="g1-lowstate-reader",
            daemon=True,
        )
        self._reader_thread.start()

    def _read_loop(self) -> None:  # pragma: no cover - hardware dependency
        while not self._stop.is_set():
            message = self._subscriber.Read()
            if message is not None:
                with self._state_lock:
                    self._state = message
                    self._state_time = time.monotonic()
            self._stop.wait(0.001)

    def _fresh_state(self) -> Any:
        with self._state_lock:
            state, timestamp = self._state, self._state_time
        if state is None:
            raise RuntimeError("no G1 rt/lowstate sample has been received")
        if time.monotonic() - timestamp > self.state_timeout:
            raise RuntimeError("G1 rt/lowstate is stale; refusing to command")
        return state

    def wait_for_state(self, timeout: float = 5.0) -> None:
        deadline = time.monotonic() + float(timeout)
        while time.monotonic() < deadline:
            try:
                self._fresh_state()
                return
            except RuntimeError:
                time.sleep(0.01)
        raise TimeoutError("timed out waiting for G1 rt/lowstate")

    def read_right_arm_positions(self) -> Vector:
        state = self._fresh_state()
        return np.array(
            [state.motor_state[index].q for index in self.arm_indices],
            dtype=float,
        )

    def read_motor_positions(self, indices: tuple[int, ...]) -> Vector:
        state = self._fresh_state()
        if any(index < 0 or index >= 29 for index in indices):
            raise ValueError("G1 motor index must be between 0 and 28")
        return np.array([state.motor_state[index].q for index in indices], dtype=float)

    def _gains(self, index: int) -> tuple[float, float]:
        """Position gains per motor, overridable from configuration.

        The stock values come from the supplied G1 script, which carried no
        instrument. A mounted tool loads the wrist far more heavily, and the
        holding torque available at a joint is only ``kp * the command lead
        limit`` -- so these and ``max_position_command_lead_rad`` have to be
        raised together, or the wrist sags and the command follows it down.
        """
        if index in self.joint_gains:
            return self.joint_gains[index]
        if index in {19, 20, 21, 26, 27, 28}:
            return 55.0, 1.5
        if index in {4, 10, 15, 16, 17, 18, 22, 23, 24, 25}:
            return 65.0, 3.0
        return 300.0, 5.0

    def enable(self) -> None:
        if not self.allow_motion:
            raise PermissionError(
                "G1 motion is disabled; pass the explicit hardware motion gates"
            )
        state = self._fresh_state()
        if self._command is None or self._publisher is None:
            raise RuntimeError("connect() must complete before enable()")
        self._command.mode_pr = 0
        self._command.mode_machine = state.mode_machine
        for index in G1_CONTROLLED_BODY_INDICES:
            motor = self._command.motor_cmd[index]
            motor.mode = 1
            motor.q = float(state.motor_state[index].q)
            motor.dq = 0.0
            motor.tau = 0.0
            motor.kp, motor.kd = self._gains(index)
        self._last_command = self.read_right_arm_positions()
        self._enabled = True

    def send_right_arm_position(
        self,
        target: ArrayLike,
        dt: float | None = None,
        velocity: ArrayLike | None = None,
    ) -> Vector:
        """Command the arm; ``velocity`` is the joint-rate feed-forward, if any.

        Without it every motor's ``dq`` target is zero, so the motor's own
        ``kd * (dq - qdot)`` term brakes all commanded motion and the joint
        trails its target by ``kd / kp`` seconds (25 ms at 200/5) before
        inertia adds more. With it, the D term damps only the error from the
        motion being commanded. Omitted, this is the transport as it was.
        """
        if not self._enabled:
            raise RuntimeError("G1 transport is not enabled")
        requested = _finite_vector(target, 7, "G1 right-arm target")
        previous = self._last_command
        if previous is None:
            previous = self.read_right_arm_positions()
        # Budget the step over the time that actually elapsed. Using the nominal
        # period instead silently clips whenever the loop runs slower than its
        # configured rate, and clipping some joints of a QP solution but not
        # others breaks the very RCM constraint the solution was built to hold.
        step_dt = self.control_dt if dt is None else max(float(dt), 1e-4)
        maximum_delta = self.max_joint_velocity * step_dt
        limited = previous + np.clip(
            requested - previous, -maximum_delta, maximum_delta
        )
        # Clipped to the same limit the position step is, so the feed-forward
        # never asks a motor to move faster than its own target is allowed to.
        feedforward = (
            np.zeros(7)
            if velocity is None
            else np.clip(
                _finite_vector(velocity, 7, "G1 joint velocity feed-forward"),
                -self.max_joint_velocity,
                self.max_joint_velocity,
            )
        )
        for index, value, rate in zip(
            self.arm_indices, limited, feedforward, strict=True
        ):
            self._command.motor_cmd[index].q = float(value)
            self._command.motor_cmd[index].dq = float(rate)
        self._command.crc = self._crc.Crc(self._command)
        self._publisher.Write(self._command)
        self._last_command = limited
        return limited.copy()

    def hold_measured(self) -> None:
        if self._enabled:
            self.send_right_arm_position(self.read_right_arm_positions())

    def close(self) -> None:
        if self._enabled:
            try:
                for _ in range(10):
                    self.hold_measured()
                    time.sleep(self.control_dt)
            except Exception:
                pass
        self._enabled = False
        self._stop.set()
        if self._reader_thread is not None:
            self._reader_thread.join(timeout=1.0)


# The historical name. Kept so nothing that imports it breaks; new code should
# use UnitreeLowCmdArm and say which arm it means.
UnitreeLowCmdRightArm = UnitreeLowCmdArm


class G1ArmMerger:
    """The single owner of ``rt/lowcmd`` for a two-arm run.

    Modelled directly on ``G1_29_ArmController`` in
    ``robot_arm_both_arms_user_study.py``, which is the arrangement already
    proven on this robot: one publisher, one ``LowCmd_``, every joint except the
    two arms locked at its pose when the controller armed, and a publish thread
    running at a fixed rate independent of whoever sets the targets.

    **The leg and waist behaviour is deliberately identical to a single-arm
    run.** Every motor is claimed and held at its enable-time position, with the
    same gains ``UnitreeLowCmdArm._gains`` picks. That is what the single-arm
    stack has always done and what the user study does; this class is not the
    place to change it.

    Two arms feed it, each from its own OS process, so neither arm's control
    loop shares an interpreter with the other. It arms itself on the first
    target it receives -- which is the measured pose, published by
    ``RemoteArmTransport.enable`` precisely so that arming cannot move an arm --
    and from then on publishes continuously, because the G1 reverts to its own
    behaviour the moment ``rt/lowcmd`` stops arriving.
    """

    def __init__(
        self,
        network_interface: str,
        *,
        allow_motion: bool,
        control_dt: float = 1.0 / 250.0,
        max_joint_velocity: float = 0.35,
        state_timeout: float = 0.10,
        state_gap_limit: float = 1.0,
        joint_gains: dict[Any, Any] | None = None,
        velocity_stale_s: float = 0.02,
    ) -> None:
        self.network_interface = str(network_interface)
        self.allow_motion = bool(allow_motion)
        self.control_dt = float(control_dt)
        self.max_joint_velocity = float(max_joint_velocity)
        self.state_timeout = float(state_timeout)
        # How long rt/lowstate may be missing before this loop STOPS writing
        # rt/lowcmd instead of holding through the gap. Defaults to the arm
        # side's stream_gap_hold_seconds, so both ends of the run give up on a
        # vanished robot at the same moment.
        self.state_gap_limit = max(float(state_gap_limit), float(state_timeout))
        self.joint_gains = {
            int(index): (float(pair[0]), float(pair[1]))
            for index, pair in (joint_gains or {}).items()
        }
        # How old an arm's velocity feed-forward may be before it goes out as
        # zero. An arm sends at its loop rate (~4 ms), so five of those is a
        # stalled arm, not a late message. Its POSITION is still held -- that
        # is the whole point of the merger -- but a held position must not
        # carry the velocity of the motion it was in when the arm stopped.
        self.velocity_stale_s = max(float(velocity_stale_s), 0.0)
        self._lock = threading.Lock()
        self._targets: dict[int, float] = {}
        self._velocities: dict[int, tuple[float, float]] = {}
        self._armed = False
        self._state_lock = threading.Lock()
        self._state: Any | None = None
        self._state_time = 0.0
        self._publisher: Any | None = None
        self._subscriber: Any | None = None
        self._command: Any | None = None
        self._crc: Any | None = None
        self._stop = threading.Event()
        self._threads: list[threading.Thread] = []
        self._published = 0
        # A LATCH, not a flag: once this loop has stopped trusting the robot's
        # state it must not resume on its own. See publish_once.
        self.faulted = threading.Event()
        self._fault: str | None = None
        self._holding = False

    @property
    def fault_reason(self) -> str | None:
        """Why this merger stopped writing rt/lowcmd, if it has."""
        return self._fault

    def _latch_fault(self, reason: str) -> None:
        if self._fault is None:
            self._fault = reason
            # The console may be gone -- this runs during a teardown as often
            # as not -- and losing the message must not cost the latch.
            try:
                print(f"arm-merger FAULT: {reason}", flush=True)
            except OSError:
                pass
        self.faulted.set()

    def state_age(self) -> float | None:
        """Seconds since the last ``rt/lowstate``, or None if none ever came."""
        with self._state_lock:
            state, timestamp = self._state, self._state_time
        if state is None:
            return None
        return time.monotonic() - timestamp

    # Same table as UnitreeLowCmdArm._gains, so a merged run and a single-arm
    # run stiffen every joint identically.
    def _gains(self, index: int) -> tuple[float, float]:
        if index in self.joint_gains:
            return self.joint_gains[index]
        if index in {19, 20, 21, 26, 27, 28}:
            return 55.0, 1.5
        if index in {4, 10, 15, 16, 17, 18, 22, 23, 24, 25}:
            return 65.0, 3.0
        return 300.0, 5.0

    def connect(self) -> None:
        try:
            from unitree_sdk2py.core.channel import (
                ChannelFactoryInitialize,
                ChannelPublisher,
                ChannelSubscriber,
            )
            from unitree_sdk2py.idl.default import unitree_hg_msg_dds__LowCmd_
            from unitree_sdk2py.idl.unitree_hg.msg.dds_ import LowCmd_, LowState_
            from unitree_sdk2py.utils.crc import CRC
        except ImportError as exc:
            raise RuntimeError(
                "install Unitree's unitree_sdk2_python before connecting to G1"
            ) from exc
        if self.network_interface:
            ChannelFactoryInitialize(0, self.network_interface)
        else:
            ChannelFactoryInitialize(0)
        self._publisher = ChannelPublisher("rt/lowcmd", LowCmd_)
        self._publisher.Init()
        self._subscriber = ChannelSubscriber("rt/lowstate", LowState_)
        self._subscriber.Init()
        self._command = unitree_hg_msg_dds__LowCmd_()
        self._crc = CRC()
        reader = threading.Thread(
            target=self._read_loop, name="merger-lowstate-reader", daemon=True
        )
        reader.start()
        self._threads.append(reader)

    def _read_loop(self) -> None:  # pragma: no cover - hardware dependency
        while not self._stop.is_set():
            message = self._subscriber.Read()
            if message is not None:
                with self._state_lock:
                    self._state = message
                    self._state_time = time.monotonic()
            self._stop.wait(0.001)

    def fresh_state(self) -> Any:
        with self._state_lock:
            state, timestamp = self._state, self._state_time
        if state is None:
            raise RuntimeError("no G1 rt/lowstate sample has been received")
        if time.monotonic() - timestamp > self.state_timeout:
            raise RuntimeError("G1 rt/lowstate is stale; refusing to command")
        return state

    def wait_for_state(self, timeout: float = 5.0) -> None:
        deadline = time.monotonic() + float(timeout)
        while time.monotonic() < deadline:
            try:
                self.fresh_state()
                return
            except RuntimeError:
                time.sleep(0.01)
        raise TimeoutError("timed out waiting for G1 rt/lowstate")

    def set_targets(
        self,
        indices: Sequence[int],
        values: ArrayLike,
        velocities: ArrayLike | None = None,
    ) -> None:
        """Record one arm's targets. Called from a ROS callback, not the loop.

        ``velocities`` is that arm's joint-rate feed-forward. A message without
        it CLEARS any the same joints carried before, so an arm that turns the
        feed-forward off, or holds, stops sending velocity at once rather than
        when it goes stale.
        """
        vector = np.asarray(values, dtype=float).reshape(-1)
        if len(vector) != len(indices) or not np.all(np.isfinite(vector)):
            return
        rates = None
        if velocities is not None:
            rates = np.asarray(velocities, dtype=float).reshape(-1)
            if len(rates) != len(indices) or not np.all(np.isfinite(rates)):
                rates = None
        now = time.monotonic()
        with self._lock:
            for slot, (index, value) in enumerate(zip(indices, vector, strict=True)):
                self._targets[int(index)] = float(value)
                if rates is None:
                    self._velocities.pop(int(index), None)
                else:
                    self._velocities[int(index)] = (float(rates[slot]), now)

    def _arm(self) -> None:
        """Lock every joint at its current pose, arms included. Once."""
        state = self.fresh_state()
        self._command.mode_pr = 0
        self._command.mode_machine = state.mode_machine
        for index in G1_CONTROLLED_BODY_INDICES:
            motor = self._command.motor_cmd[index]
            motor.mode = 1
            motor.q = float(state.motor_state[index].q)
            motor.dq = 0.0
            motor.tau = 0.0
            motor.kp, motor.kd = self._gains(index)
        self._armed = True

    def publish_once(self) -> bool:
        """One whole-body message. Returns False while nothing has armed yet.

        Arming happens here, on the first target from either arm, so that the
        body snapshot is taken at a moment when at least one arm is already
        commanding its own measured pose.
        """
        # The latch is checked HERE and not only in publish_loop, because the
        # thing it guards against is precisely a robot that comes BACK: once
        # rt/lowstate returns the age check below would pass again and the old
        # armed command would resume. Nothing releases this but a new process.
        if self.faulted.is_set():
            return False
        with self._lock:
            targets = dict(self._targets)
            velocities = dict(self._velocities)
            armed = self._armed
            if targets and not armed:
                self._arm()
                armed = True
        if not armed or self._command is None:
            return False
        # ------------------------------------------------------------------
        # rt/lowstate is the only evidence the robot is still there, and this
        # loop is the only thing writing rt/lowcmd. A SHORT gap is held through
        # on purpose -- the same decision `stream_gap_hold_seconds` records on
        # the arm side, for the DDS discovery bursts that starve a 250 Hz loop
        # -- but a gap this loop can no longer explain has to stop the writing
        # rather than ride it out.
        #
        # 2026-09-10, and this is what the check is FOR: an orphaned merger
        # kept publishing an armed command straight through a POWER CYCLE of
        # the robot. Nothing here looked at rt/lowstate after _arm(), so the
        # first message the G1 received when it came back up carried the RCM
        # pose at kp 300 for every motor, and it jolted there before the
        # operator could initialise anything.
        #
        # The velocity clamp below is no defence against that. It limits this
        # command against the LAST COMMAND, which was already at that pose, so
        # the step it measures is zero no matter how far the robot has moved or
        # how long it has been gone. Refusing to write is the only defence.
        age = self.state_age()
        if age is None or age > self.state_gap_limit:
            self._latch_fault(
                "rt/lowstate has been missing for "
                + ("this whole run" if age is None else f"{age:.2f} s")
                + f" (limit {self.state_gap_limit:.2f} s); refusing to keep "
                "commanding the G1. Restart the run against the robot that is "
                "actually there -- this process will not resume on its own."
            )
            return False
        if age > self.state_timeout:
            if not self._holding:
                self._holding = True
                try:
                    print(
                        f"arm-merger holding: rt/lowstate stale by "
                        f"{age * 1e3:.0f} ms, still sending the last command",
                        flush=True,
                    )
                except OSError:
                    pass
        elif self._holding:
            self._holding = False
            try:
                print("arm-merger: rt/lowstate is back", flush=True)
            except OSError:
                pass
        step = self.max_joint_velocity * self.control_dt
        now = time.monotonic()
        for index, value in targets.items():
            # Clamped against what actually went OUT last time, which is the
            # point of doing it here rather than in each arm: two arms are then
            # limited against the one message the robot sees.
            previous = self._command.motor_cmd[index].q
            self._command.motor_cmd[index].q = float(
                np.clip(value, previous - step, previous + step)
            )
            # Velocity feed-forward goes out only while it is fresh and the
            # robot's state is: a stalled arm, or a merger riding out a
            # rt/lowstate gap, holds its position with dq = 0 -- the behaviour
            # every run had before feed-forward existed.
            rate = 0.0
            entry = velocities.get(index)
            if (
                entry is not None
                and not self._holding
                and now - entry[1] <= self.velocity_stale_s
            ):
                rate = float(
                    np.clip(entry[0], -self.max_joint_velocity, self.max_joint_velocity)
                )
            self._command.motor_cmd[index].dq = rate
        self._command.crc = self._crc.Crc(self._command)
        self._publisher.Write(self._command)
        self._published += 1
        return True

    def publish_loop(self) -> None:
        """Publish at a fixed rate, independent of either arm's loop rate.

        Decoupled on purpose, exactly as ``G1_29_ArmController`` does it. The
        two arms run in separate processes at whatever rate they achieve, and
        the wire sees a steady stream carrying the latest of each. An arm that
        stalls or dies is held at its last target rather than dropping the
        robot.
        """
        if not self.allow_motion:
            raise PermissionError(
                "G1 motion is disabled; pass the explicit hardware motion gates"
            )
        next_tick = time.monotonic()
        while not self._stop.is_set() and not self.faulted.is_set():
            self.publish_once()
            next_tick += self.control_dt
            delay = next_tick - time.monotonic()
            if delay > 0.0:
                time.sleep(delay)
            else:
                next_tick = time.monotonic()

    def close(self) -> None:
        self._stop.set()
        for thread in self._threads:
            thread.join(timeout=1.0)
        self._threads.clear()


class RemoteArmTransport:
    """One arm's transport when a MERGER owns ``rt/lowcmd``.

    Same surface as ``UnitreeLowCmdArm`` -- ``run_hardware`` cannot tell them
    apart -- but it never writes the G1 command topic. It reads ``rt/lowstate``
    directly, which is read-only and takes any number of subscribers, and
    PUBLISHES its seven joint targets for the merger to pick up.

    **Why this exists.** Two arms need two control loops, and two control loops
    in one CPython process cost far more than two processes: measured on this
    workspace, two `rclpy` executors co-located run 3.6x the CPU of one and
    three run 7.3x, because `_wait_for_ready_callbacks` rebuilds the whole
    WaitSet in Python on every wake and each `MultiThreadedExecutor`'s three
    threads queue up on one GIL. As separate OS processes the same two arms hold
    247 Hz each at negligible CPU; sharing one interpreter they fall to 190 Hz
    and burn most of a core. So each arm gets its own process -- and then
    exactly one process may still own ``rt/lowcmd``, because that topic carries
    the whole body in every message. This class is the arm side of that split;
    ``g1_arm_merger`` is the other.

    The velocity clamp deliberately does NOT live here. It belongs with the
    publisher, so that two arms are limited against the message actually going
    out rather than against each process's private idea of it -- the same place
    ``G1_29_ArmController.clip_arm_q_target`` puts it in
    ``robot_arm_both_arms_user_study.py``. ``run_hardware`` never reads this
    method's return value, so nothing upstream depends on the difference.
    """

    def __init__(
        self,
        network_interface: str,
        *,
        publish: Callable[[Sequence[str], ArrayLike], None],
        joint_names: Sequence[str],
        allow_motion: bool = False,
        control_dt: float = 0.004,
        max_joint_velocity: float = 0.35,
        state_timeout: float = 0.10,
        arm_indices: tuple[int, ...] = G1_RIGHT_ARM_INDICES,
    ) -> None:
        self.arm_indices = tuple(int(index) for index in arm_indices)
        if len(self.arm_indices) != 7 or any(
            index < 0 or index >= 29 for index in self.arm_indices
        ):
            raise ValueError("arm_indices must be seven G1 motor indices in 0..28")
        self.arm_side = (
            "left" if self.arm_indices == G1_LEFT_ARM_INDICES
            else "right" if self.arm_indices == G1_RIGHT_ARM_INDICES
            else "custom"
        )
        self.joint_names = [str(name) for name in joint_names]
        if len(self.joint_names) != 7:
            raise ValueError(
                "joint_names must be the arm's seven model joint names, "
                f"got {len(self.joint_names)}"
            )
        self._publish = publish
        self.network_interface = str(network_interface)
        self.allow_motion = bool(allow_motion)
        self.control_dt = float(control_dt)
        self.max_joint_velocity = float(max_joint_velocity)
        self.state_timeout = float(state_timeout)
        self._state_lock = threading.Lock()
        self._state: Any | None = None
        self._state_time = 0.0
        self._subscriber: Any | None = None
        self._enabled = False
        self._last_command: Vector | None = None
        self._stop = threading.Event()
        self._reader_thread: threading.Thread | None = None

    def connect(self) -> None:
        try:
            from unitree_sdk2py.core.channel import (
                ChannelFactoryInitialize,
                ChannelSubscriber,
            )
            from unitree_sdk2py.idl.unitree_hg.msg.dds_ import LowState_
        except ImportError as exc:
            raise RuntimeError(
                "install Unitree's unitree_sdk2_python before connecting to G1"
            ) from exc
        if self.network_interface:
            ChannelFactoryInitialize(0, self.network_interface)
        else:
            ChannelFactoryInitialize(0)
        # Subscriber only. No ChannelPublisher is created here at all, which is
        # the property that makes two of these safe on one robot.
        self._subscriber = ChannelSubscriber("rt/lowstate", LowState_)
        self._subscriber.Init()
        self._reader_thread = threading.Thread(
            target=self._read_loop,
            name=f"g1-lowstate-reader-{self.arm_side}",
            daemon=True,
        )
        self._reader_thread.start()

    def _read_loop(self) -> None:  # pragma: no cover - hardware dependency
        while not self._stop.is_set():
            message = self._subscriber.Read()
            if message is not None:
                with self._state_lock:
                    self._state = message
                    self._state_time = time.monotonic()
            self._stop.wait(0.001)

    def _fresh_state(self) -> Any:
        with self._state_lock:
            state, timestamp = self._state, self._state_time
        if state is None:
            raise RuntimeError("no G1 rt/lowstate sample has been received")
        if time.monotonic() - timestamp > self.state_timeout:
            raise RuntimeError("G1 rt/lowstate is stale; refusing to command")
        return state

    def wait_for_state(self, timeout: float = 5.0) -> None:
        deadline = time.monotonic() + float(timeout)
        while time.monotonic() < deadline:
            try:
                self._fresh_state()
                return
            except RuntimeError:
                time.sleep(0.01)
        raise TimeoutError("timed out waiting for G1 rt/lowstate")

    def read_right_arm_positions(self) -> Vector:
        state = self._fresh_state()
        return np.array(
            [state.motor_state[index].q for index in self.arm_indices], dtype=float
        )

    def read_motor_positions(self, indices: tuple[int, ...]) -> Vector:
        state = self._fresh_state()
        if any(index < 0 or index >= 29 for index in indices):
            raise ValueError("G1 motor index must be between 0 and 28")
        return np.array([state.motor_state[index].q for index in indices], dtype=float)

    def enable(self) -> None:
        if not self.allow_motion:
            raise PermissionError(
                "G1 motion is disabled; pass the explicit hardware motion gates"
            )
        # Arming is the merger's to do, and it does it on the first target it
        # receives. Publishing the measured pose here is that first target: it
        # is a no-op command by construction, so the merger snapshots the body
        # and starts publishing without the arm moving.
        self._last_command = self.read_right_arm_positions()
        self._enabled = True
        self._publish(self.joint_names, self._last_command)

    def send_right_arm_position(
        self,
        target: ArrayLike,
        dt: float | None = None,
        velocity: ArrayLike | None = None,
    ) -> Vector:
        if not self._enabled:
            raise RuntimeError("G1 transport is not enabled")
        requested = _finite_vector(target, 7, f"G1 {self.arm_side}-arm target")
        if velocity is None:
            # Two arguments exactly as before, so a run without feed-forward
            # publishes byte-identical messages.
            self._publish(self.joint_names, requested)
        else:
            # The merger clips and ages it; see G1ArmMerger.publish_once.
            self._publish(
                self.joint_names,
                requested,
                _finite_vector(velocity, 7, f"G1 {self.arm_side}-arm velocity"),
            )
        self._last_command = requested
        return requested.copy()

    def hold_measured(self) -> None:
        if self._enabled:
            self.send_right_arm_position(self.read_right_arm_positions())

    def close(self) -> None:
        # No hold-and-decay loop here. UnitreeLowCmdArm re-sends the measured
        # pose ten times on the way out because it is about to stop being the
        # only publisher; this transport was never the publisher, and the merger
        # keeps holding this arm's last target for exactly that reason.
        self._enabled = False
        self._stop.set()
        if self._reader_thread is not None:
            self._reader_thread.join(timeout=1.0)
            self._reader_thread = None


class SimulatedG1RightArm:
    """Stand-in for the G1 transport that integrates commands instead of DDS.

    Deliberately exposes the same surface as UnitreeLowCmdRightArm so
    run_hardware drives it without knowing the difference: the alignment, the
    handover and the MTM teleoperation are the same code paths that run on the
    robot. Tracking is modelled as a first-order lag so the loop is not
    unrealistically perfect.
    """

    def __init__(
        self,
        start_posture: ArrayLike,
        *,
        control_dt: float = 0.004,
        max_joint_velocity: float = 0.35,
        tracking_lag_s: float = 0.02,
        publish: Any = None,
    ) -> None:
        self.control_dt = float(control_dt)
        self.max_joint_velocity = float(max_joint_velocity)
        self.tracking_lag_s = max(float(tracking_lag_s), 1e-4)
        self._measured = _finite_vector(start_posture, 7, "simulated start posture")
        self._last_command: Vector | None = None
        self._enabled = False
        self._publish = publish

    def connect(self) -> None:
        print("simulated G1: no DDS, commands are integrated locally")

    def wait_for_state(self, timeout: float = 5.0) -> None:
        return None

    def read_right_arm_positions(self) -> Vector:
        return self._measured.copy()

    def read_motor_positions(self, indices: tuple[int, ...]) -> Vector:
        # Locked waist joints read as commanded, so the arming check passes.
        return np.zeros(len(indices))

    def enable(self) -> None:
        self._last_command = self._measured.copy()
        self._enabled = True

    def send_right_arm_position(
        self,
        target: ArrayLike,
        dt: float | None = None,
        velocity: ArrayLike | None = None,
    ) -> Vector:
        # ``velocity`` is accepted for surface parity and ignored: the
        # first-order lag below has no D term for a feed-forward to cancel.
        if not self._enabled:
            raise RuntimeError("simulated G1 is not enabled")
        requested = _finite_vector(target, 7, "G1 right-arm target")
        previous = self._last_command
        if previous is None:
            previous = self._measured.copy()
        step_dt = self.control_dt if dt is None else max(float(dt), 1e-4)
        limited = previous + np.clip(
            requested - previous,
            -self.max_joint_velocity * step_dt,
            self.max_joint_velocity * step_dt,
        )
        self._last_command = limited
        blend = min(step_dt / self.tracking_lag_s, 1.0)
        self._measured = self._measured + blend * (limited - self._measured)
        if self._publish is not None:
            self._publish(self._measured)
        return limited.copy()

    def hold_measured(self) -> None:
        if self._enabled:
            self.send_right_arm_position(self._measured)

    def close(self) -> None:
        self._enabled = False


# rclpy is per-PROCESS, and a bimanual run puts TWO bridges in one process.
# rclpy.init() a second time raises, and the first bridge to close would call
# rclpy.shutdown() out from under the one still running its arm -- which stops
# the ROS side of a live teleoperation loop as a side effect of the OTHER arm
# standing down. Reference-counted, so a single-arm run still does exactly one
# init and one shutdown.
_ROS_CONTEXT_LOCK = threading.Lock()
_ROS_CONTEXT_USERS = 0


class Ros2HardwareBridge:
    """Thread-safe ROS 2 boundary for the existing MTM and H4HR topics."""

    def __init__(
        self,
        settings: dict[str, Any],
        ros_arguments: list[str] | None,
        *,
        arm_joint_names: Sequence[str] | None = None,
        instrument_joint_names: Sequence[str] | None = None,
        tool_joint_names: Sequence[str] | None = None,
        node_name: str = "humanoid_rcm_hardware_teleop",
        subscribe_commands: bool = False,
        rcm_frames: Sequence[str] = (),
    ) -> None:
        try:
            import rclpy
            from geometry_msgs.msg import PoseStamped
            from rclpy.executors import MultiThreadedExecutor
            from rclpy.node import Node
            from sensor_msgs.msg import Joy, JointState
            from std_msgs.msg import Bool, String
        except ImportError as exc:  # pragma: no cover - ROS dependency
            raise RuntimeError(
                "source a ROS 2 workspace providing rclpy, geometry_msgs, "
                "sensor_msgs and std_msgs"
            ) from exc
        self._rclpy = rclpy
        self._JointState = JointState
        self._String = String
        global _ROS_CONTEXT_USERS
        with _ROS_CONTEXT_LOCK:
            if _ROS_CONTEXT_USERS == 0:
                rclpy.init(args=ros_arguments)
            _ROS_CONTEXT_USERS += 1
        # Named, because a bimanual run puts TWO of these on one graph and ROS 2
        # only warns about a duplicate node name -- it does not stop it, and the
        # result is two nodes indistinguishable in `ros2 node list`.
        self.node = Node(str(node_name))
        # The real model joint names this arm owns, used by publish_sim_arm so
        # that two pipelines sharing /humanoid_rcm/sim_arm stay separable. See
        # publish_sim_arm for why the generic names are still emitted too.
        self._sim_arm_names = list(arm_joint_names) if arm_joint_names else []
        self._sim_instrument_names = (
            list(instrument_joint_names) if instrument_joint_names else []
        )
        # How the tool's four joints are labelled on the command and state
        # topics. Defaults to the only set that has ever existed -- see
        # prefixed_tool_joint_names for what a second instrument does.
        self._tool_joint_names = (
            tuple(str(name) for name in tool_joint_names)
            if tool_joint_names
            else H4HR_JOINT_NAMES
        )
        if len(self._tool_joint_names) != 4:
            raise ValueError(
                "tool_joint_names must have 4 entries [roll, pitch, yaw, grip], "
                f"got {len(self._tool_joint_names)}"
            )
        self._lock = threading.Lock()
        self._mtm_position: Vector | None = None
        self._mtm_rotation: Matrix | None = None
        self._mtm_pose_sequence = 0
        self._mtm_pose_time = 0.0
        self._gripper_angle: float | None = None
        self._gripper_time = 0.0
        self._clutch_pressed = True
        self._rcm_point: Vector | None = None
        self._psm_positions: Vector | None = None
        self._psm_grip: float | None = None
        self._psm_state_time = 0.0
        self._enable_requested = False
        self._estop_latched = False
        self._command_position: Vector | None = None
        self._command_rotation: Matrix | None = None
        self._command_sequence = 0
        self._command_time = 0.0
        self._command_delta_position: Vector | None = None
        self._command_delta_rotation: Matrix | None = None
        self.expected_base_frame = str(settings.get("base_frame", "pelvis"))
        # Frame ids taken AS the base frame on the RCM topic. base_frame alone
        # unless the run asked for the detector (--rcm-source detected), whose
        # ArUco publisher stamps the G1 base under another name -- see
        # hardware.ros2.detected_rcm_frames and SYSTEM_CONTEXT 9.26. The MTM
        # pose check below is deliberately not widened with it.
        self._rcm_frames = {self.expected_base_frame, *(str(f) for f in rcm_frames)}
        self.gripper_joint = settings.get("gripper_joint")
        pose_topic = str(settings.get("mtm_pose_topic", "/MTMR/measured_cp"))
        gripper_topic = str(
            settings.get("mtm_gripper_topic", "/MTMR/gripper/measured_js")
        )
        clutch_topic = str(settings.get("clutch_topic", "/footpedals/clutch"))
        rcm_topic = str(settings.get("rcm_topic", "/RCM_pose_right"))
        psm_state_topic = str(settings.get("psm_state_topic", "/joint_states"))
        enable_topic = str(settings.get("enable_topic", "/humanoid_rcm/enable"))
        estop_topic = str(settings.get("estop_topic", "/h4hr/estop"))
        psm_command_topic = str(
            settings.get("psm_command_topic", "/h4hr/joint_command")
        )
        status_topic = str(settings.get("status_topic", "/humanoid_rcm/status"))
        # Cartesian command inputs.  The defaults are RIGHT-handed, matching
        # measured_cp.py's namespaces so the read and write sides are symmetric;
        # each config carries its own pair, and the left one must say so.
        servo_cp_topic = str(
            settings.get("servo_cp_topic", "/surgie_hand_right/servo_cp")
        )
        servo_cp_rel_topic = str(
            settings.get("servo_cp_rel_topic", "/surgie_hand_right/servo_cp_rel")
        )
        self.node.create_subscription(PoseStamped, pose_topic, self._pose_callback, 10)
        self.node.create_subscription(
            JointState, gripper_topic, self._gripper_callback, 10
        )
        self.node.create_subscription(Joy, clutch_topic, self._clutch_callback, 10)
        self.node.create_subscription(PoseStamped, rcm_topic, self._rcm_callback, 10)
        self.node.create_subscription(
            JointState, psm_state_topic, self._psm_state_callback, 10
        )
        self.node.create_subscription(Bool, enable_topic, self._enable_callback, 10)
        self.node.create_subscription(Bool, estop_topic, self._estop_callback, 10)
        if subscribe_commands:
            # Created ONLY under --command-source servo.  Subscribing in MTM
            # mode would be functionally harmless -- the mapper never reads
            # these fields -- but it makes the subscriber count on servo_cp
            # meaningless, and that count is exactly what a client checks to
            # find out whether anything will act on what it sends.  A tool that
            # reports "1 subscriber" for a command nothing consumes is worse
            # than no check at all.
            self.node.create_subscription(
                PoseStamped, servo_cp_topic, self._servo_cp_callback, 10
            )
            self.node.create_subscription(
                PoseStamped, servo_cp_rel_topic, self._servo_cp_rel_callback, 10
            )
        self._psm_publisher = self.node.create_publisher(
            JointState, psm_command_topic, 10
        )
        self._sim_publisher = self.node.create_publisher(
            JointState, "/humanoid_rcm/sim_arm", 10
        )
        self._status_publisher = self.node.create_publisher(String, status_topic, 10)
        self._executor = MultiThreadedExecutor(num_threads=3)
        self._executor.add_node(self.node)
        self._thread = threading.Thread(
            target=self._executor.spin, name="rcm-ros2", daemon=True
        )
        self._thread.start()

    def _pose_callback(self, message: Any) -> None:
        try:
            orientation = message.pose.orientation
            rotation = quaternion_xyzw_to_rotation(
                (orientation.x, orientation.y, orientation.z, orientation.w)
            )
            position = _finite_vector(
                (
                    message.pose.position.x,
                    message.pose.position.y,
                    message.pose.position.z,
                ),
                3,
                "MTM position",
            )
        except ValueError as exc:
            self.node.get_logger().warning(f"ignoring invalid MTM pose: {exc}")
            return
        now = time.monotonic()
        with self._lock:
            self._mtm_position = position
            self._mtm_rotation = rotation
            self._mtm_pose_sequence += 1
            self._mtm_pose_time = now

    def _gripper_callback(self, message: Any) -> None:
        angle: float | None = None
        names = list(message.name)
        positions = list(message.position)
        if self.gripper_joint and self.gripper_joint in names:
            index = names.index(self.gripper_joint)
            if index < len(positions):
                angle = float(positions[index])
        if angle is None:
            for index, name in enumerate(names):
                lowered = name.lower()
                if index < len(positions) and any(
                    hint in lowered for hint in ("gripper", "jaw", "actuator")
                ):
                    angle = float(positions[index])
                    break
        if angle is None and len(positions) == 1:
            angle = float(positions[0])
        if angle is None or not np.isfinite(angle):
            return
        with self._lock:
            self._gripper_angle = angle
            self._gripper_time = time.monotonic()

    def _clutch_callback(self, message: Any) -> None:
        pressed = not message.buttons or bool(message.buttons[0])
        with self._lock:
            self._clutch_pressed = pressed

    def _command_pose(self, message: Any, label: str) -> tuple[Vector, Matrix] | None:
        """Parse a base-frame PoseStamped, or return None having said why.

        The frame is CHECKED here, unlike the master pose callback: these
        commands are authored by whatever is driving the stack, and a pose
        arriving in some other frame would be tracked to the wrong place in
        silence.  measured_cp.py stamps ``pelvis``, so a correct client already
        matches.
        """
        frame = str(message.header.frame_id)
        if frame and frame != self.expected_base_frame:
            self.node.get_logger().error(
                f"ignoring {label} in {frame!r}; expected "
                f"{self.expected_base_frame!r}"
            )
            return None
        try:
            orientation = message.pose.orientation
            rotation = quaternion_xyzw_to_rotation(
                (orientation.x, orientation.y, orientation.z, orientation.w)
            )
            position = _finite_vector(
                (
                    message.pose.position.x,
                    message.pose.position.y,
                    message.pose.position.z,
                ),
                3,
                f"{label} position",
            )
        except ValueError as exc:
            self.node.get_logger().warning(f"ignoring invalid {label}: {exc}")
            return None
        return position, rotation

    def _servo_cp_callback(self, message: Any) -> None:
        parsed = self._command_pose(message, "servo_cp")
        if parsed is None:
            return
        position, rotation = parsed
        now = time.monotonic()
        with self._lock:
            self._command_position = position
            self._command_rotation = rotation
            self._command_sequence += 1
            self._command_time = now

    def _servo_cp_rel_callback(self, message: Any) -> None:
        parsed = self._command_pose(message, "servo_cp_rel")
        if parsed is None:
            return
        position, rotation = parsed
        now = time.monotonic()
        with self._lock:
            # Accumulate rather than latch.  Two deltas arriving inside one
            # control cycle must both land, so position sums and rotation
            # composes; snapshot() then drains the pair.  A latched last-value
            # field would silently drop one of them.
            if self._command_delta_position is None:
                self._command_delta_position = position
            else:
                self._command_delta_position = self._command_delta_position + position
            if self._command_delta_rotation is None:
                self._command_delta_rotation = rotation
            else:
                self._command_delta_rotation = rotation @ self._command_delta_rotation
            self._command_time = now

    def _rcm_callback(self, message: Any) -> None:
        frame = str(message.header.frame_id)
        if frame and frame not in self._rcm_frames:
            expected = " or ".join(repr(name) for name in sorted(self._rcm_frames))
            self.node.get_logger().error(
                f"ignoring RCM pose in {frame!r}; expected {expected}"
            )
            return
        try:
            point = _finite_vector(
                (
                    message.pose.position.x,
                    message.pose.position.y,
                    message.pose.position.z,
                ),
                3,
                "RCM point",
            )
        except ValueError:
            return
        with self._lock:
            # The RCM is latched at arming by the runtime. Updating this cache
            # while active cannot silently move the controller's constraint.
            self._rcm_point = point

    def _psm_state_callback(self, message: Any) -> None:
        values = dict(zip(message.name, message.position))
        # Names this side does not own are ignored, which is what lets a second
        # instrument share /joint_states without either arm reading the other's
        # wrist. A stream carrying none of them is simply some other publisher.
        if not all(name in values for name in self._tool_joint_names[:3]):
            return
        positions = np.array([values[name] for name in self._tool_joint_names[:3]])
        grip = values.get(self._tool_joint_names[3])
        if not np.all(np.isfinite(positions)):
            return
        with self._lock:
            self._psm_positions = positions
            self._psm_grip = None if grip is None else float(grip)
            self._psm_state_time = time.monotonic()

    def _enable_callback(self, message: Any) -> None:
        with self._lock:
            self._enable_requested = bool(message.data)

    def _estop_callback(self, message: Any) -> None:
        if message.data:
            with self._lock:
                self._estop_latched = True

    def snapshot(self) -> RosSnapshot:
        with self._lock:
            # Relative commands are CONSUMED here.  run_hardware calls this
            # exactly once per control cycle, which is what makes draining in a
            # reader correct; a second caller in the same cycle would eat the
            # other's deltas.
            delta_position = self._command_delta_position
            delta_rotation = self._command_delta_rotation
            self._command_delta_position = None
            self._command_delta_rotation = None
            return RosSnapshot(
                None if self._mtm_position is None else self._mtm_position.copy(),
                None if self._mtm_rotation is None else self._mtm_rotation.copy(),
                self._mtm_pose_sequence,
                self._mtm_pose_time,
                self._gripper_angle,
                self._gripper_time,
                self._clutch_pressed,
                None if self._rcm_point is None else self._rcm_point.copy(),
                None if self._psm_positions is None else self._psm_positions.copy(),
                self._psm_grip,
                self._psm_state_time,
                self._enable_requested,
                self._estop_latched,
                None if self._command_position is None else self._command_position.copy(),
                None if self._command_rotation is None else self._command_rotation.copy(),
                self._command_sequence,
                self._command_time,
                delta_position,
                delta_rotation,
            )

    def publish_psm(self, hardware_positions: ArrayLike, grip: float) -> None:
        positions = _finite_vector(hardware_positions, 3, "PSM command")
        if not np.isfinite(grip):
            raise ValueError("PSM grip command must be finite")
        message = self._JointState()
        message.header.stamp = self.node.get_clock().now().to_msg()
        message.name = list(self._tool_joint_names)
        message.position = [*map(float, positions), float(grip)]
        self._psm_publisher.publish(message)

    def publish_arm_target(
        self,
        names: Sequence[str],
        values: ArrayLike,
        velocities: ArrayLike | None = None,
    ) -> None:
        """Publish one arm's seven joint targets for ``g1_arm_merger``.

        On the SAME pre-existing ``/humanoid_rcm/sim_arm`` topic
        ``publish_sim_arm`` uses, under the arm's real model joint names --
        which are disjoint between the two configs, so the two arms are already
        separable there without inventing a topic. That is the standing rule
        this graph is under, and it is the same device section 9.9 uses on
        ``/h4hr/joint_command``.

        The topic's name says "sim" for historical reasons; nothing about it is
        simulation-specific -- it has always carried "this arm's joint values,
        by name" and that is exactly what the merger needs. A run that wants the
        two streams under distinct names can remap it per side at launch, the
        same way the instrument chain's nameless topics are separated.

        Only the real names are emitted here. ``publish_sim_arm`` also emits
        generic ``arm{i}`` aliases for single-arm viewers; those are ambiguous
        between two arms by construction, and a merger keying on them would
        write whichever message arrived last onto both arms.
        """
        message = self._JointState()
        message.header.stamp = self.node.get_clock().now().to_msg()
        message.name = [str(name) for name in names]
        message.position = [
            float(value) for value in np.asarray(values, dtype=float).reshape(-1)
        ]
        # JointState's own velocity field, on the same message: the joint-rate
        # feed-forward rides with the targets it belongs to, so no topic is
        # invented and the two can never arrive out of step. Left empty when
        # there is none, which the merger reads as dq = 0.
        if velocities is not None:
            message.velocity = [
                float(value)
                for value in np.asarray(velocities, dtype=float).reshape(-1)
            ]
        self._sim_publisher.publish(message)

    def publish_sim_arm(
        self,
        arm: ArrayLike,
        instrument: ArrayLike | None = None,
        grip: float | None = None,
    ) -> None:
        """Broadcast the simulated joint state so a viewer can mirror it.

        Every value is published TWICE: once under the generic ``arm{i}`` /
        ``psm{i}`` / ``grip`` names this has always used, and once under the
        real model joint name from the config (``right_shoulder_pitch_joint``,
        ``lnd_left_roll``, ...) when the caller supplied them.

        The duplication is the whole point of this method for a bimanual run.
        ``/humanoid_rcm/sim_arm`` is a fixed topic name, so two simulated
        pipelines publish onto it together, and under the generic names their
        messages are INDISTINGUISHABLE -- a viewer keying on ``arm0..arm6``
        writes whichever message arrived last onto the same model bodies and
        the two arms flicker as one.  The real joint names are disjoint between
        the two configs, so a viewer keying on those separates them with no new
        topic, which is the constraint that rules this graph out.

        The generic names stay because they are what the single-arm consumers
        read -- ``visualize_setup.py --follow`` and ``motion_acc_anlysis.py``.
        In a two-arm run those names are ambiguous and a consumer using them
        sees the arms alternate; that is no worse than today, where a two-arm
        run is not possible at all.  Prefer the real names in new code.
        """
        message = self._JointState()
        message.header.stamp = self.node.get_clock().now().to_msg()
        arm_values = list(np.asarray(arm, dtype=float).reshape(-1))
        values = list(arm_values)
        names = [f"arm{i}" for i in range(len(values))]
        instrument_values: list[float] = []
        if instrument is not None:
            instrument_values = list(np.asarray(instrument, dtype=float).reshape(-1))
            values += instrument_values
            names += [f"psm{i}" for i in range(len(instrument_values))]
        if grip is not None and np.isfinite(grip):
            values.append(float(grip))
            names.append("grip")

        # The named aliases. zip() stops at the shorter side on purpose: a
        # config listing fewer joints than the arm reports should alias what it
        # can rather than raise inside the 250 Hz loop.
        for name, value in zip(self._sim_arm_names, arm_values):
            names.append(name)
            values.append(float(value))
        for name, value in zip(self._sim_instrument_names, instrument_values):
            names.append(name)
            values.append(float(value))
        if (
            grip is not None
            and np.isfinite(grip)
            and self._sim_instrument_names
        ):
            # Side-qualified by the instrument's own first joint rather than by
            # a parsed "left"/"right" prefix, so it stays correct whatever the
            # joints are called.
            names.append(f"grip_of_{self._sim_instrument_names[0]}")
            values.append(float(grip))

        message.name = names
        message.position = [float(v) for v in values]
        self._sim_publisher.publish(message)

    def publish_status(self, status: str) -> None:
        message = self._String()
        message.data = str(status)
        self._status_publisher.publish(message)

    def close(self) -> None:
        global _ROS_CONTEXT_USERS
        self._executor.shutdown()
        self._thread.join(timeout=2.0)
        self.node.destroy_node()
        with _ROS_CONTEXT_LOCK:
            _ROS_CONTEXT_USERS = max(0, _ROS_CONTEXT_USERS - 1)
            last = _ROS_CONTEXT_USERS == 0
        if last and self._rclpy.ok():
            self._rclpy.shutdown()


